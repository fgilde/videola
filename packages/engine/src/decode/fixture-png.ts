// Test code. This file is never re-exported from `index.ts` and cannot reach a bundle.
//
// A real PNG rather than a string that claims to be one, because the two things worth testing about
// a still both need real bytes: the sniff that tells a picture from a container reads the signature,
// and the browser harness hands these to a real `createImageBitmap`. Two by two and opaque red, so a
// frame drawn from it can be read back and recognised.

const RED_2X2_PNG = [
  0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52,
  0x00, 0x00, 0x00, 0x02, 0x00, 0x00, 0x00, 0x02, 0x08, 0x06, 0x00, 0x00, 0x00, 0x72, 0xb6, 0x0d,
  0x24, 0x00, 0x00, 0x00, 0x11, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9c, 0x63, 0xf8, 0xcf, 0xc0, 0xf0,
  0x1f, 0x84, 0x19, 0x60, 0x0c, 0x00, 0x47, 0xca, 0x07, 0xf9, 0x67, 0x59, 0x6e, 0xb7, 0x00, 0x00,
  0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82,
];

export const PNG_WIDTH = 2;
export const PNG_HEIGHT = 2;

export function tinyPng(): File {
  return new File([new Uint8Array(RED_2X2_PNG)], "logo.png", { type: "image/png" });
}

// The same picture as OPFS hands it back: content-addressed bytes with no name and no type, which
// is the case the byte sniff exists for.
export function tinyPngBytes(): File {
  return new File([new Uint8Array(RED_2X2_PNG)], "");
}
